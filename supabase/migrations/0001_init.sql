create or replace function public.delete_vehicle(p_vehicle_id uuid, p_token text) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_team_id uuid;
begin
  select team_id into v_team_id from public.vehicles where id = p_vehicle_id;
  if v_team_id is null or not public.is_valid_team_token(v_team_id, p_token) then
    raise exception 'invalid token';
  end if;
  delete from public.vehicles where id = p_vehicle_id;
end;
$$;

create or replace function public.toggle_like(p_vehicle_id uuid, p_fingerprint text) returns int
language plpgsql security definer set search_path = public as $$
declare
  v_liked boolean;
  v_count int;
begin
  select exists(select 1 from public.likes where vehicle_id = p_vehicle_id and fingerprint = p_fingerprint) into v_liked;
  if v_liked then
    delete from public.likes where vehicle_id = p_vehicle_id and fingerprint = p_fingerprint;
  else
    insert into public.likes (vehicle_id, fingerprint) values (p_vehicle_id, p_fingerprint)
    on conflict do nothing;
  end if;
  select likes_count into v_count from public.vehicles where id = p_vehicle_id;
  return v_count;
end;
$$;

create or replace function public.admin_verify(p_pin text) returns boolean
language sql security definer set search_path = public as $$
  select public.is_admin_pin(p_pin);
$$;

create or replace function public.admin_get_team_token(p_pin text, p_team_id uuid) returns text
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin_pin(p_pin) then raise exception 'invalid pin'; end if;
  return (select edit_token from public.team_secrets where team_id = p_team_id);
end;
$$;

create or replace function public.admin_set_status(p_pin text, p_kind text, p_id uuid, p_status text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin_pin(p_pin) then raise exception 'invalid pin'; end if;
  if p_kind = 'team' then
    update public.teams set status = p_status where id = p_id;
  elsif p_kind = 'vehicle' then
    update public.vehicles set status = p_status where id = p_id;
  else
    raise exception 'invalid kind';
  end if;
end;
$$;

create or replace function public.admin_set_featured(p_pin text, p_kind text, p_id uuid, p_featured boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin_pin(p_pin) then raise exception 'invalid pin'; end if;
  if p_kind = 'team' then
    update public.teams set featured = p_featured where id = p_id;
  elsif p_kind = 'vehicle' then
    update public.vehicles set featured = p_featured where id = p_id;
  else
    raise exception 'invalid kind';
  end if;
end;
$$;

