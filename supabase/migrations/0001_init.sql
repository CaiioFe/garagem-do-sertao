create extension if not exists pgcrypto;

-- ===== teams =====
create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  name text not null,
  city text,
  state text,
  logo_url text,
  cover_url text,
  description text,
  instagram text,
  whatsapp text,
  website text,
  sponsors text[] not null default '{}',
  founded_year int,
  sertoes_participations int not null default 0,
  titles_general int not null default 0,
  titles_category int not null default 0,
  featured boolean not null default false,
  status text not null default 'active' check (status in ('active','hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.team_secrets (
  team_id uuid primary key references public.teams(id) on delete cascade,
  edit_token text not null
);

-- ===== vehicles (as cartas) =====
create table if not exists public.vehicles (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.teams(id) on delete cascade,
  slug text unique not null,
  card_number int generated by default as identity unique,
  name text not null,
  brand text,
  model text,
  year int,
  race_number text,
  category_id text not null,
  type text not null check (type in ('carro','utv','moto','quadri','apoio')),
  photo_url text,
  pilot_name text,
  pilot_photo_url text,
  pilot_city text,
  navigator_name text,
  navigator_photo_url text,
  specs jsonb not null default '{}',
  history jsonb not null default '{}',
  description text,
  sponsors text[] not null default '{}',
  likes_count int not null default 0,
  featured boolean not null default false,
  status text not null default 'active' check (status in ('active','hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vehicles_team_id_idx on public.vehicles(team_id);
create index if not exists vehicles_category_id_idx on public.vehicles(category_id);
create index if not exists vehicles_likes_idx on public.vehicles(likes_count desc);
create index if not exists teams_slug_idx on public.teams(slug);
create index if not exists vehicles_slug_idx on public.vehicles(slug);

-- ===== likes =====
create table if not exists public.likes (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  fingerprint text not null,
  created_at timestamptz not null default now(),
  unique(vehicle_id, fingerprint)
);

create or replace function public.handle_like_insert() returns trigger
language plpgsql as $$
begin
  update public.vehicles set likes_count = likes_count + 1 where id = new.vehicle_id;
  return new;
end;
$$;

create or replace function public.handle_like_delete() returns trigger
language plpgsql as $$
begin
  update public.vehicles set likes_count = greatest(0, likes_count - 1) where id = old.vehicle_id;
  return old;
end;
$$;

drop trigger if exists on_like_insert on public.likes;
create trigger on_like_insert after insert on public.likes
  for each row execute function public.handle_like_insert();

drop trigger if exists on_like_delete on public.likes;
create trigger on_like_delete after delete on public.likes
  for each row execute function public.handle_like_delete();

