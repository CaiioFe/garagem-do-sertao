-- ===== helper: slug generator com sufixo se duplicado =====
create or replace function public.next_free_slug(p_table text, p_base text) returns text
language plpgsql as $$
declare
  candidate text := p_base;
  i int := 1;
  exists_row boolean;
begin
  loop
    execute format('select exists(select 1 from public.%I where slug = $1)', p_table) into exists_row using candidate;
    exit when not exists_row;
    i := i + 1;
    candidate := p_base || '-' || i;
  end loop;
  return candidate;
end;
$$;

-- ===== token helpers =====
create or replace function public.gen_edit_token() returns text
language sql as $$
  select upper(substr(encode(gen_random_bytes(6), 'hex'), 1, 4)) || '-' || upper(substr(encode(gen_random_bytes(6), 'hex'), 5, 4));
$$;

create or replace function public.is_admin_pin(p_pin text) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  h text;
begin
  select value into h from public.app_config where key = 'admin_pin_hash';
  if h is null or p_pin is null then return false; end if;
  return h = crypt(p_pin, h);
end;
$$;

create or replace function public.is_valid_team_token(p_team_id uuid, p_token text) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  real_token text;
begin
  if p_token is null then return false; end if;
  if public.is_admin_pin(p_token) then return true; end if;
  select edit_token into real_token from public.team_secrets where team_id = p_team_id;
  return real_token is not null and real_token = p_token;
end;
$$;

-- ===== RPCs públicas =====
create or replace function public.create_team(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_slug text;
  v_token text;
begin
  v_slug := public.next_free_slug('teams', p->>'slug');
  v_token := public.gen_edit_token();
  insert into public.teams (slug, name, city, state, description, instagram, whatsapp, website, founded_year)
  values (v_slug, p->>'name', p->>'city', p->>'state', p->>'description', p->>'instagram', p->>'whatsapp', p->>'website',
          nullif(p->>'founded_year','')::int)
  returning id into v_id;
  insert into public.team_secrets (team_id, edit_token) values (v_id, v_token);
  return jsonb_build_object('id', v_id, 'slug', v_slug, 'edit_token', v_token);
end;
$$;

create or replace function public.verify_team_token(p_team_id uuid, p_token text) returns boolean
language sql security definer set search_path = public as $$
  select public.is_valid_team_token(p_team_id, p_token);
$$;

create or replace function public.update_team(p_team_id uuid, p_token text, p jsonb) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_valid_team_token(p_team_id, p_token) then
    raise exception 'invalid token';
  end if;
  update public.teams set
    name = coalesce(p->>'name', name),
    city = coalesce(p->>'city', city),
    state = coalesce(p->>'state', state),
    logo_url = coalesce(p->>'logo_url', logo_url),
    cover_url = coalesce(p->>'cover_url', cover_url),
    description = coalesce(p->>'description', description),
    instagram = coalesce(p->>'instagram', instagram),
    whatsapp = coalesce(p->>'whatsapp', whatsapp),
    website = coalesce(p->>'website', website),
    sponsors = coalesce((select array_agg(x) from jsonb_array_elements_text(p->'sponsors') x), sponsors),
    founded_year = coalesce(nullif(p->>'founded_year','')::int, founded_year)
  where id = p_team_id;
end;
$$;

create or replace function public.create_vehicle(p_team_id uuid, p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_slug text;
begin
  if not public.is_valid_team_token(p_team_id, p_token) then
    raise exception 'invalid token';
  end if;
  v_slug := public.next_free_slug('vehicles', p->>'slug');
  insert into public.vehicles (team_id, slug, name, brand, model, year, race_number, category_id, type,
                                photo_url, pilot_name, pilot_photo_url, pilot_city, navigator_name, navigator_photo_url,
                                specs, history, description, sponsors)
  values (p_team_id, v_slug, p->>'name', p->>'brand', p->>'model', nullif(p->>'year','')::int, p->>'race_number',
          p->>'category_id', p->>'type', p->>'photo_url', p->>'pilot_name', p->>'pilot_photo_url', p->>'pilot_city',
          p->>'navigator_name', p->>'navigator_photo_url',
          coalesce(p->'specs', '{}'::jsonb), coalesce(p->'history', '{}'::jsonb), p->>'description',
          coalesce((select array_agg(x) from jsonb_array_elements_text(p->'sponsors') x), '{}'))
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'slug', v_slug);
end;
$$;

